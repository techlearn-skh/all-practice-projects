CREATE TABLE IF NOT EXISTS app_roles (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(40) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS app_users (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, username VARCHAR(80) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL, enabled BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS user_roles (
 user_id BIGINT NOT NULL, role_id BIGINT NOT NULL, PRIMARY KEY(user_id,role_id),
 FOREIGN KEY(user_id) REFERENCES app_users(id), FOREIGN KEY(role_id) REFERENCES app_roles(id)
);
CREATE TABLE IF NOT EXISTS refresh_tokens (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, token_hash CHAR(64) NOT NULL UNIQUE,
 username VARCHAR(80) NOT NULL, expires_at TIMESTAMP NOT NULL,
 revoked BOOLEAN NOT NULL DEFAULT FALSE, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
